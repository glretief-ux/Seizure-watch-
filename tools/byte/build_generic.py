"""Build byte.js: the config-driven version of Byte for any static page.

Source of truth for the look, animation, voice and chat engine is swatch/byte_helper.html.
Output: tools/byte/dist/byte.js (copy it next to a page, add a byte-config.js and two script tags).
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, 'swatch', 'byte_helper.html'), encoding='utf-8').read()

css = src[src.index('<style>') + 7:src.index('</style>')]
markup = src[src.index('</style>') + 8:src.index('<script>')].strip()
js = src[src.index('<script>') + 8:src.index('</script>')]

def between(a, b, text=js):
    i = text.index(a); j = text.index(b, i)
    return text[i:j]

matching = between('  /* ---------- matching ---------- */', '  /* ---------- chat window ---------- */')
chat_top = between('  /* ---------- chat window ---------- */', '  function ask(q){')
voice = between('  /* ---------- talking to Byte', "  form.addEventListener('submit'")
openclose = between('  /* ---------- open / close ---------- */', '  /* ---------- Byte on the page')
acts = js[js.index('  /* ---------- Byte on the page'):js.rindex('})();')]

# the intro clip is optional in the generic version
markup = markup.replace('poster="assets/byte-poster.jpg"', 'poster="__POSTER__"').replace('src="assets/byte-helper.mp4"', 'src="__VIDEO__"')
markup = markup.replace('<span id="byteTitle">Ask Byte</span>', '<span id="byteTitle">__TITLE__</span>')
markup = re.sub(r'<div class="bnote">.*?</div>', '<div class="bnote">__NOTE__</div>', markup, flags=re.S)
markup = markup.replace('placeholder="Ask a question, e.g. how is risk scored?"', 'placeholder="__PLACEHOLDER__"')

head = r"""/* Byte, the help helper. Generated by tools/byte/build_generic.py - edit swatch/byte_helper.html there, not this file.
   Needs a byte-config.js before it:  window.BYTE_CONFIG = {...}  (see README of the Byte tool). */
(function(){
  if(document.getElementById('byteBtn'))return;
  var C=window.BYTE_CONFIG||{};
  var NAME=C.name||'this page',NOUN=C.noun||'page';
  var CSS=%s;
  var HTML=%s;
  var st=document.createElement('style');st.textContent=CSS;document.head.appendChild(st);
  var box=document.createElement('div');
  box.innerHTML=HTML.replace('__TITLE__','Ask Byte').replace('__PLACEHOLDER__',(C.placeholder||'Ask a question, e.g. how do I use this?').replace(/"/g,'&quot;'))
    .replace('__NOTE__',C.note||'I\'m not a live AI. I answer from a built-in list of questions about this page, so short, simple questions work best.')
    .replace('__VIDEO__',C.video||'').replace('__POSTER__',C.poster||'');
  while(box.firstChild)document.body.appendChild(box.firstChild);
  if(!C.video){var vw=document.getElementById('byteVidWrap');if(vw)vw.parentNode.removeChild(vw);}
  var g=function(i){return document.getElementById(i);};
  var btn=g('byteBtn'),modal=g('byteModal'),vid=g('byteVideo')||{pause:function(){}},nudge=g('byteNudge'),closeB=g('byteClose'),
      log=g('byteLog'),form=g('byteForm'),inp=g('byteQ'),chips=g('byteChips'),vtog=g('byteVidTog'),vbox=g('byteVidBox');
  if(C.nudge)nudge.textContent=C.nudge;
  var lastFocus=null,greeted=false;
  var reduce=!!(window.matchMedia&&matchMedia('(prefers-reduced-motion:reduce)').matches);
  var E=(C.faqs||[]).slice();
  E.push({k:['who are you','what are you','what can you do','are you ai','are you a bot','chatbot','byte','about you'],
    a:'<p>I\'m Byte, the helper for '+NAME+'. I\'m not a live AI model: I answer from a built-in list of questions and I can jump to the right place on the page.</p>'});
  E.push({k:['thanks','thank you','thx','cheers','merci','great'],a:'<p>You\'re welcome! Ask me anything else.</p>'});
  E.push({k:['hi','hello','hey','good morning','good evening','yo'],a:'<p>Hi! What would you like to know about '+NAME+'?</p>'});
  var STARTERS=C.starters||[];

  /* ---------- go to a place on the page ---------- */
  function A(label,fn){return {l:label,f:fn};}
  function go(find,focusId){closeH(true);
    setTimeout(function(){var el=find();if(!el)return;
      el.scrollIntoView({behavior:reduce?'auto':'smooth',block:'start'});
      if(focusId){setTimeout(function(){try{el.focus({preventScroll:true});}catch(e){}},600);}},80);}
  function toBtn(o){return A(o.label,function(){
    if(o.href){location.href=o.href;return;}
    if(o.click){var c=document.querySelector(o.click);if(c){closeH(true);setTimeout(function(){c.click();if(o.focus){setTimeout(function(){var f=document.querySelector(o.focus);if(f){try{f.focus();}catch(e){}}},200);}},80);}return;}
    if(o.set){var f=document.querySelector(o.set[0]);if(f){f.value=o.set[1];f.dispatchEvent(new Event('input',{bubbles:true}));f.dispatchEvent(new Event('change',{bubbles:true}));}}
    go(function(){return document.querySelector(o.go||o.focus||o.set&&o.set[0]);},o.focus);});}
  E.forEach(function(e){if(e.go)e.act=e.go.map(toBtn);});
  function setQ(v){var e=C.search&&document.querySelector(C.search);if(!e)return false;e.value=v;e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}));return true;}

""" % (json.dumps(css), json.dumps(markup))

ask = r"""  function ask(q){
    q=(q||'').trim();if(!q)return;
    addUser(q);var m=best(q);
    var typ=addTyping();
    setTimeout(function(){
      if(typ.parentNode)typ.parentNode.removeChild(typ);
      if(m){addByte(m.a,m.act);speakText(m.a);}
      else{var acts=[];if(C.search&&q.length<=60){acts.push(A('Search for "'+q+'"',function(){if(setQ(q))go(function(){return document.querySelector(C.search);},true);}));}
        var fb=C.fallback||'<p>I don\'t have an answer for that one yet. Try a shorter question, or tap one of the suggestions below.</p>';
        speakText(fb);addByte(fb,acts);}
    },700);}
"""
openclose = openclose.replace("Ask me how to use this dashboard, or tap one of the questions below.", "'+(C.greeting||'Ask me how to use '+NAME+', or tap one of the questions below.')+'")
tail = "\n})();\n"
out = head + matching + chat_top + ask + voice + "  form.addEventListener('submit',function(e){e.preventDefault();var q=inp.value;inp.value='';ask(q);});\n" + \
      "  STARTERS.forEach(function(s){var b=document.createElement('button');b.type='button';b.textContent=s[0];b.addEventListener('click',function(){ask(s[1]);});chips.appendChild(b);});\n" + \
      "  if(vtog)vtog.addEventListener('click',function(){var open=vbox.hidden;vbox.hidden=!open;vtog.setAttribute('aria-expanded',open?'true':'false');vtog.textContent=open?'Hide the intro clip':'Watch the 15-second intro clip';if(!open){try{vid.pause();}catch(e){}}});\n\n" + \
      openclose + acts + tail
os.makedirs(os.path.join(ROOT, 'tools', 'byte', 'dist'), exist_ok=True)
open(os.path.join(ROOT, 'tools', 'byte', 'dist', 'byte.js'), 'w', encoding='utf-8').write(out)
print('byte.js', len(out), 'bytes')
